// Generates supabase/migrations/20261106000000_locations_gazetteer.sql from
// east_africa_locations_v2.csv (the Postgres twin of the vendor's T-SQL script).
// Run: node scripts/build-locations-migration.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const csvPath = join(root, "east_africa_locations_v2.csv");
const outPath = join(root, "supabase", "migrations", "20261106000000_locations_gazetteer.sql");

/** Minimal quote-aware CSV parser (the dataset quotes fields containing commas). */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 1;
        } else quoted = false;
      } else field += ch;
      continue;
    }
    if (ch === '"') {
      quoted = true;
    } else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i += 1;
      row.push(field);
      field = "";
      if (row.some((v) => v !== "")) rows.push(row);
      row = [];
    } else field += ch;
  }
  row.push(field);
  if (row.some((v) => v !== "")) rows.push(row);
  return rows;
}

const q = (value) => `'${String(value).replaceAll("'", "''")}'`;
const qOrNull = (value) => {
  const trimmed = String(value ?? "").trim();
  return trimmed ? q(trimmed) : "NULL";
};
const qIntOrNull = (value) => {
  const trimmed = String(value ?? "").trim();
  return trimmed && Number.isFinite(Number(trimmed)) ? String(Number(trimmed)) : "NULL";
};

const raw = readFileSync(csvPath, "utf8").replace(/^\uFEFF/, "");
const rows = parseCsv(raw);
const header = rows[0].map((h) => h.trim());
const expected = ["LocationCode", "Name", "LocationType", "ParentLocationCode", "AdminLevel", "Aliases", "Notes"];
if (expected.some((name, index) => header[index] !== name)) {
  throw new Error(`Unexpected CSV header: ${header.join(",")}`);
}
const data = rows.slice(1);

const seen = new Set();
for (const row of data) {
  const code = row[0].trim();
  if (seen.has(code)) throw new Error(`Duplicate LocationCode: ${code}`);
  seen.add(code);
}

const TYPES = ["COUNTRY", "STATE", "ADMIN1", "ADMIN2", "ADMIN_AREA", "DIVISION", "CITY", "TOWN", "NEIGHBOURHOOD"];

const valueTuples = data.map((row) => {
  const [code, name, type, parent, level, aliases, notes] = [
    row[0].trim(),
    row[1].trim(),
    row[2].trim().toUpperCase(),
    row[3].trim(),
    row[4],
    row[5] ?? "",
    row[6] ?? "",
  ];
  if (!TYPES.includes(type)) throw new Error(`Unknown LocationType for ${code}: ${type}`);
  const aliasList = String(aliases)
    .split("|")
    .map((a) => a.trim().toLowerCase())
    .filter((a) => a && a !== name.toLowerCase());
  const aliasesSql = aliasList.length
    ? `ARRAY[${aliasList.map(q).join(",")}]::text[]`
    : `'{}'::text[]`;
  const verified = type === "COUNTRY" || type === "CITY" ? "true" : "false";
  return `    (${q(code)}, ${qOrNull(parent)}, ${q(code.slice(0, 2))}, ${q(name)}, ${q(name.toLowerCase())}, ${q(type)}, ${qIntOrNull(level)}, ${aliasesSql}, ${qOrNull(notes)}, ${verified})`;
});

const CHUNK = 250;
const seedStatements = [];
for (let start = 0; start < valueTuples.length; start += CHUNK) {
  seedStatements.push(
    `INSERT INTO public.locations (code, parent_code, country_code, name, normalized_name, location_type, admin_level, aliases, notes, is_verified)\nVALUES\n${valueTuples
      .slice(start, start + CHUNK)
      .join(",\n")}\nON CONFLICT (code) DO UPDATE\nSET parent_code = EXCLUDED.parent_code,\n    country_code = EXCLUDED.country_code,\n    name = EXCLUDED.name,\n    normalized_name = EXCLUDED.normalized_name,\n    location_type = EXCLUDED.location_type,\n    admin_level = EXCLUDED.admin_level,\n    aliases = EXCLUDED.aliases,\n    notes = EXCLUDED.notes,\n    is_verified = EXCLUDED.is_verified,\n    is_active = true;`
  );
}

const sql = `-- East Africa locations gazetteer (seeded from east_africa_locations_v2.csv).
-- A single shared geographic service for onboarding, search and discovery:
-- countries, first-level regions, districts, cities/towns and neighbourhoods for
-- KE, RW, BI, CD, SS and UG, with aliases for tolerant search. Registration
-- location stays on listings (country/city/neighborhood text + the optional
-- location_code pointer); multi-location coverage lives in
-- provider_service_areas (primary / secondary / remote).
-- Generated by scripts/build-locations-migration.mjs; regenerate instead of
-- hand-editing the seed rows below.

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE IF NOT EXISTS public.locations (
    code text NOT NULL PRIMARY KEY,
    parent_code text REFERENCES public.locations(code) DEFERRABLE INITIALLY DEFERRED,
    country_code char(2) NOT NULL,
    name text NOT NULL,
    normalized_name text NOT NULL,
    location_type text NOT NULL CHECK (location_type IN (${TYPES.map((t) => `'${t}'`).join(", ")})),
    admin_level smallint,
    aliases text[] NOT NULL DEFAULT '{}'::text[],
    notes text,
    is_active boolean NOT NULL DEFAULT true,
    is_verified boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- array_to_string() is only STABLE, which Postgres rejects inside an index
-- expression (SQLSTATE 42P17). Joining a text[] with a constant separator is
-- provably immutable, so wrap it in an IMMUTABLE function and index that.
-- plpgsql (not sql) on purpose: the planner never inlines plpgsql bodies, so
-- the STABLE array_to_string inside can never leak back into the index check.
CREATE OR REPLACE FUNCTION public.location_aliases_text(p_aliases text[])
RETURNS text
LANGUAGE plpgsql IMMUTABLE PARALLEL SAFE
AS $$
BEGIN
    RETURN array_to_string(p_aliases, ' | ');
END;
$$;

GRANT EXECUTE ON FUNCTION public.location_aliases_text(text[]) TO anon, authenticated;

CREATE INDEX IF NOT EXISTS idx_locations_parent ON public.locations (parent_code);
CREATE INDEX IF NOT EXISTS idx_locations_country_type ON public.locations (country_code, location_type);
CREATE INDEX IF NOT EXISTS idx_locations_normalized_name ON public.locations (normalized_name);
CREATE INDEX IF NOT EXISTS idx_locations_name_trgm ON public.locations USING gin (name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_locations_aliases_trgm ON public.locations USING gin (public.location_aliases_text(aliases) gin_trgm_ops);

ALTER TABLE public.locations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Locations are publicly readable" ON public.locations;
CREATE POLICY "Locations are publicly readable" ON public.locations
    FOR SELECT USING (is_active);

DROP POLICY IF EXISTS "Admins can manage locations" ON public.locations;
CREATE POLICY "Admins can manage locations" ON public.locations
    FOR ALL USING (public.is_admin()) WITH CHECK (public.is_admin());

GRANT SELECT ON public.locations TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.locations TO authenticated;

-- Provider service coverage: a profile registers in one place but can serve in
-- several (primary = registration area, secondary = named towns, remote = any).
CREATE TABLE IF NOT EXISTS public.provider_service_areas (
    id uuid NOT NULL PRIMARY KEY DEFAULT gen_random_uuid(),
    listing_id uuid NOT NULL REFERENCES public.listings(id) ON DELETE CASCADE,
    location_code text NOT NULL REFERENCES public.locations(code) ON DELETE CASCADE,
    coverage text NOT NULL DEFAULT 'secondary' CHECK (coverage IN ('primary', 'secondary', 'remote')),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT provider_service_areas_unique_area UNIQUE (listing_id, location_code)
);

CREATE INDEX IF NOT EXISTS idx_provider_service_areas_listing ON public.provider_service_areas (listing_id);
CREATE INDEX IF NOT EXISTS idx_provider_service_areas_location ON public.provider_service_areas (location_code);

ALTER TABLE public.provider_service_areas ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Service areas are publicly readable" ON public.provider_service_areas;
CREATE POLICY "Service areas are publicly readable" ON public.provider_service_areas
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Admins can manage all service areas" ON public.provider_service_areas;
CREATE POLICY "Admins can manage all service areas" ON public.provider_service_areas
    FOR ALL USING (public.is_admin()) WITH CHECK (public.is_admin());

GRANT SELECT ON public.provider_service_areas TO anon, authenticated;

-- Optional gazetteer pointer for the exact registration node (city or hood).
ALTER TABLE public.listings ADD COLUMN IF NOT EXISTS location_code text;
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'listings_location_code_fkey' AND conrelid = 'public.listings'::regclass
    ) THEN
        ALTER TABLE public.listings
            ADD CONSTRAINT listings_location_code_fkey
            FOREIGN KEY (location_code) REFERENCES public.locations(code)
            ON DELETE SET NULL;
    END IF;
END;
$$;
CREATE INDEX IF NOT EXISTS idx_listings_location_code ON public.listings (location_code);

-- Autocomplete + cross-category search over the gazetteer. Walks parents
-- recursively to build a "UG / Central / Kampala / Kololo" display path.
CREATE OR REPLACE FUNCTION public.search_locations(
    p_query text,
    p_country_code text DEFAULT NULL,
    p_limit integer DEFAULT 12
)
RETURNS TABLE (
    code text,
    name text,
    location_type text,
    parent_code text,
    country_code char(2),
    admin_level smallint,
    display_path text
)
LANGUAGE sql STABLE SECURITY INVOKER
SET search_path = public
AS $$
    -- RECURSIVE is required: the "up" item below self-references to build paths.
    WITH RECURSIVE hits AS (
        SELECT l.code, l.name, l.location_type, l.parent_code, l.country_code, l.admin_level
        FROM public.locations l
        WHERE l.is_active
          AND (p_country_code IS NULL OR l.country_code = p_country_code)
          AND (
            l.normalized_name LIKE '%' || lower(trim(p_query)) || '%'
            -- Same expression as the alias trigram index, so the planner can use it.
            OR public.location_aliases_text(l.aliases) LIKE '%' || lower(trim(p_query)) || '%'
          )
        ORDER BY
            (l.normalized_name = lower(trim(p_query))) DESC,
            (l.normalized_name LIKE lower(trim(p_query)) || '%') DESC,
            CASE l.location_type
                WHEN 'CITY' THEN 0 WHEN 'TOWN' THEN 1 WHEN 'NEIGHBOURHOOD' THEN 2 ELSE 3 END,
            l.name
        LIMIT greatest(1, least(COALESCE(p_limit, 12), 40))
    ),
    up (code, parent_code, names) AS (
        SELECT h.code, h.parent_code, ARRAY[h.name]
        FROM hits h
        UNION ALL
        SELECT u.code, p.parent_code, p.name || u.names
        FROM up u
        JOIN public.locations p ON p.code = u.parent_code
    ),
    paths AS (
        SELECT DISTINCT ON (code) code, names
        FROM up
        ORDER BY code, cardinality(names) DESC
    )
    SELECT h.code, h.name, h.location_type, h.parent_code, h.country_code, h.admin_level,
           array_to_string(ph.names, ' / ')
    FROM hits h
    JOIN paths ph ON ph.code = h.code;
$$;

GRANT EXECUTE ON FUNCTION public.search_locations(text, text, integer) TO anon, authenticated;

-- Replace a provider's coverage set atomically (owner or admin only).
-- p_areas: [{"code": "KE-COUNTY-047", "coverage": "secondary"}, ...] (max 12).
CREATE OR REPLACE FUNCTION public.set_provider_service_areas(
    p_listing_id uuid,
    p_areas jsonb
)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    owner_id uuid;
    area jsonb;
    inserted integer := 0;
BEGIN
    SELECT user_id INTO owner_id FROM public.listings WHERE id = p_listing_id;
    IF owner_id IS NULL THEN
        RAISE EXCEPTION 'Listing not found';
    END IF;
    IF auth.uid() IS DISTINCT FROM owner_id AND NOT public.is_admin() THEN
        RAISE EXCEPTION 'Not allowed to manage this profile location';
    END IF;
    IF jsonb_typeof(p_areas) <> 'array' THEN
        RAISE EXCEPTION 'Expected a JSON array of service areas';
    END IF;

    DELETE FROM public.provider_service_areas WHERE listing_id = p_listing_id;

    FOR area IN SELECT * FROM jsonb_array_elements(p_areas)
    LOOP
        IF inserted >= 12 THEN
            EXIT;
        END IF;
        INSERT INTO public.provider_service_areas (listing_id, location_code, coverage)
        VALUES (
            p_listing_id,
            area ->> 'code',
            CASE
                WHEN area ->> 'coverage' IN ('primary', 'remote') THEN area ->> 'coverage'
                ELSE 'secondary'
            END
        )
        ON CONFLICT (listing_id, location_code) DO NOTHING;
        inserted := inserted + 1;
    END LOOP;
END;
$$;

GRANT EXECUTE ON FUNCTION public.set_provider_service_areas(uuid, jsonb) TO authenticated;

-- ---------------------------------------------------------------------------
-- Seed (${data.length} gazetteer rows, parent-first)
-- ---------------------------------------------------------------------------
${seedStatements.join("\n\n")}
`;

writeFileSync(outPath, sql, "utf8");
console.log(`Wrote ${outPath}`);
console.log(`Rows seeded: ${data.length}`);
